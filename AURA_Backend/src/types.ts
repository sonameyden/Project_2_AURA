// Mirrors the Kotlin data classes in core/model exactly — field names and enum
// constant names must match 1:1, since Moshi (on the Android side) deserializes
// by name with no @Json aliasing configured. If you rename a field on either
// side, rename it on both.

export type EnvironmentType =
  | "Heaven" | "Nature" | "Ocean" | "Dream"
  | "Romantic" | "Melancholic" | "Hopeful" | "Energetic";

export type LightingStyle = "Soft" | "Bright" | "Dramatic" | "Fading";

export type ParticleStyle =
  | "Dust" | "Rain" | "Bubbles" | "Petals" | "Stars" | "Sparks" | "None";

export type KaleidoscopeStyle =
  | "SoftOrganic" | "FluidSymmetry" | "WaveLike"
  | "SharpGeometric" | "DarkReflective" | "Floral";

export type CatBehaviorState =
  | "Idle" | "Sleeping" | "Walking" | "Stretching" | "Playing" | "Running" | "Watching";

export type TransitionStyle = "Gentle" | "Progressive" | "Sharp";

export type SongSection =
  | "Intro" | "Verse" | "PreChorus" | "Chorus" | "Bridge" | "FinalChorus" | "Outro";

/**
 * Cat behaviours used inside section timelines. `Dancing` is Project II-only,
 * so it never appears in the top-level `catBehavior` field, which the Kotlin
 * app still parses with a strict enum.
 */
export type SectionCatBehavior = CatBehaviorState | "Dancing";

/**
 * One part of a song's visual timeline. The first three fields are what the
 * Kotlin app reads; the rest are Project II additions (unknown fields are
 * ignored by older clients), letting each section carry its own look.
 */
export interface SongSectionProfile {
  section: SongSection;
  startTimeMs: number;
  intensityMultiplier: number;
  endTimeMs?: number;
  environment?: EnvironmentType;
  primaryColorHex?: string;
  secondaryColorHexes?: string[];
  lightingStyle?: LightingStyle;
  catBehavior?: SectionCatBehavior;
  /** "ai" when generated by OpenAI, "estimated" when derived from lyrics/duration. */
  source?: "ai" | "estimated";
}

export interface Song {
  id: string;
  title: string;
  artistId: string;
  artistName: string;
  albumId: string | null;
  durationMs: number;
  streamUrl: string; // R2-hosted URL
  artworkUrl: string | null;
  genre: string | null;
  releaseDate: string | null;
}

export interface Artist {
  id: string;
  name: string;
  bio: string | null;
  imageUrl: string | null;
  isVerified: boolean;
  followerCount: number;
  monthlyListeners: number;
}

export interface Album {
  id: string;
  title: string;
  artistId: string;
  artworkUrl: string | null;
  songIds: string[];
  releaseDate: string | null;
}

export interface Playlist {
  id: string;
  title: string;
  ownerId: string;
  songIds: string[];
  isPublic: boolean;
  coverColorHex: string | null;
}

export interface AtmosphereProfile {
  songId: string;
  emotion: string;
  energy: number;   // 0..1
  valence: number;  // 0..1
  environment: EnvironmentType;
  primaryColorHex: string;
  secondaryColorHexes: string[];
  lightingStyle: LightingStyle;
  particleStyle: ParticleStyle;
  kaleidoscopeStyle: KaleidoscopeStyle;
  catBehavior: CatBehaviorState;
  transitionStyle: TransitionStyle;
  resonantLyricLineIds: string[];
  sectionProfiles: SongSectionProfile[];
}

export interface LyricLine {
  id: string;
  text: string;
  startTimeMs: number;
  endTimeMs: number;
}

export interface LyricsResponse {
  songId: string;
  lines: LyricLine[];
}

export interface MoodRequest {
  moodText: string;
  recentlyPlayedSongIds: string[];
}

export interface MoodResponse {
  mode: "recommendations" | "direct_play";
  reply: string;
  songs: Song[];
  song: Song | null;
  atmosphereProfile: AtmosphereProfile | null;
}

