-- AURA prototype Library and artist metrics migration
-- Run once in the Supabase SQL editor.

alter table artists
  add column if not exists monthly_listeners int not null default 0;

create table if not exists liked_songs (
  user_id text not null,
  song_id text not null references songs(id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (user_id, song_id)
);

create table if not exists listening_history (
  id bigint generated by default as identity primary key,
  user_id text not null,
  song_id text not null references songs(id) on delete cascade,
  played_at timestamptz not null default now()
);

create index if not exists listening_history_user_played_at_idx
  on listening_history (user_id, played_at desc);

create table if not exists music_worlds (
  id uuid primary key default gen_random_uuid(),
  user_id text not null,
  name text not null,
  song_id text references songs(id) on delete set null,
  atmosphere_profile jsonb not null,
  created_at timestamptz not null default now()
);

create table if not exists playlists (
  id text primary key,
  owner_id text not null,
  title text not null,
  song_ids text[] not null default '{}',
  is_public boolean not null default false,
  cover_color_hex text,
  created_at timestamptz not null default now()
);

