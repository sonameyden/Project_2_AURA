-- Search history is one unified history per user. result_type/result_id are
-- optional metadata for the item selected from a search result.
create table if not exists search_history (
  id bigint generated by default as identity primary key,
  user_id text not null,
  query text not null,
  result_type text,
  result_id text,
  result_title text,
  searched_at timestamptz not null default now(),
  constraint search_history_result_type_check
    check (result_type is null or result_type in ('song', 'artist', 'album', 'playlist'))
);

create index if not exists search_history_user_searched_at_idx
  on search_history (user_id, searched_at desc);

create index if not exists songs_album_id_idx on songs (album_id);
create index if not exists albums_artist_id_idx on albums (artist_id);

